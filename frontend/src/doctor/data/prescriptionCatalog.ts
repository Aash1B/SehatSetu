export function searchCatalog(category: 'SYMPTOM' | 'MEDICINE' | 'LAB_TEST' | 'DIET_LIFESTYLE', query: string, maxResults = 8): string[] {
  if (!query.trim()) return [];
  const q = query.trim().toLowerCase();
  return PRESCRIPTION_CATALOG
    .filter(item => item.category === category && (
      item.displayText.toLowerCase().includes(q) ||
      item.searchKeywords.toLowerCase().includes(q)
    ))
    .slice(0, maxResults)
    .map(item => item.displayText);
}
